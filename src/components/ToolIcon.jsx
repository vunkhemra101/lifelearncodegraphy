export default function ToolIcon({ name, className = "w-4 h-4 shrink-0" }) {
  const n = (name || "").toLowerCase();

  if (n.includes("photoshop")) {
    return <PhotoshopIcon className={className} />;
  }
  if (n.includes("capcut")) {
    return <CapCutIcon className={className} />;
  }
  if (n.includes("visual studio") || n.includes("vscode") || n.includes("vs code")) {
    return <VSCodeIcon className={className} />;
  }
  if (n.includes("figma")) {
    return <FigmaIcon className={className} />;
  }
  if (n.includes("devinci") || n.includes("davinci") || n.includes("resolve")) {
    return <DaVinciResolveIcon className={className} />;
  }
  if (n.includes("illustrator")) {
    return <IllustratorIcon className={className} />;
  }

  return null;
}
